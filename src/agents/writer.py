def _build_llm() -> ChatOpenAI:
    kwargs = {
        "model": settings.openai_model,
        "max_tokens": 32768,
    }
    if settings.openai_api_key:
        kwargs["api_key"] = settings.openai_api_key
    if settings.openai_base_url:
        kwargs["base_url"] = settings.openai_base_url
    return ChatOpenAI(**kwargs)


def _group_by_topic(items: list[ExtractedItem]) -> dict[str, list[ExtractedItem]]:
    """按主题聚类新闻"""
    groups: dict[str, list[ExtractedItem]] = defaultdict(list)
    for item in items:
        primary_topic = item.topics[0] if item.topics else "Other"
        groups[primary_topic].append(item)
    return dict(groups)


def _build_fallback_markdown(items: list[ExtractedItem], today: str) -> str:
    """LLM 不可用时的降级模板渲染，与 LLM 输出格式保持一致"""
    lines = [
        f"# AI Daily — {today}",
        "",
        f"> Covering {len(items)} AI news items",
        "",
    ]

    # Top Stories: importance >= 8 的前 3 条
    top_items = [i for i in items if i.ai_score >= 8][:3]
    if top_items:
        lines.append("## 🔥 Top Stories")
        lines.append("")
        for idx, item in enumerate(top_items, 1):
            summary = item.summary or item.title
            lines.append(f"### {idx}. {item.title}")
            lines.append("")
            src = item.source_type.value
            lines.append(
                f"{summary} {item.ai_reason} "
                f"**AI Score: {item.ai_score:.1f}/10** [Source-{src}]({_origin_url(item)})"
            )
            lines.append("")

    # Featured: 按话题分组，排除已在焦点中展示的
    top_ids = {id(i) for i in top_items}
    featured = [i for i in items if i.ai_score >= 7 and id(i) not in top_ids]
    if featured:
        groups = _group_by_topic(featured)
        lines.append("## 📰 Featured")
        lines.append("")
        for topic, topic_items in groups.items():
            lines.append(f"### {topic}")
            lines.append("")
            for item in topic_items:
                summary = item.summary or item.title
                src = item.source_type.value
                lines.append(
                    f"- **{item.title}** — {summary} "
                    f"**AI Score: {item.ai_score:.1f}/10** [Source-{src}]({_origin_url(item)})"
                )
            lines.append("")

    # Quick Bites
    brief = [i for i in items if i.ai_score < 7]
    if brief:
        lines.append("## ⚡ Quick Bites")
        lines.append("")
        for item in brief:
            summary = item.summary or item.title
            src = item.source_type.value
            lines.append(
                f"- **{item.title}** — {summary} "
                f"**AI Score: {item.ai_score:.1f}/10** [Source-{src}]({_origin_url(item)})"
            )
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(f"*Generated by AI News Agent | {today}*")

    return "\n".join(lines)


