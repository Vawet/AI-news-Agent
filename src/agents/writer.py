def _normalize_source_links(markdown: str) -> str:
    """后处理：统一所有链接标签为 [Source-xxx](url) 格式"""
    import re

    # 域名 → 来源标签映射
    domain_map = {
        "x.com": "x", "twitter.com": "x",
        "reddit.com": "reddit",
        "news.ycombinator.com": "hackernews", "hn.algolia.com": "hackernews",
        "arxiv.org": "arxiv",
        "github.com": "github",
        "huggingface.co": "huggingface",
        "anthropic.com": "anthropic",
    }

    def _get_source(url: str) -> str:
        for domain, label in domain_map.items():
            if domain in url:
                return label
        return "rss"

    # 匹配所有 markdown 链接 [任意文本](url)
    def replacer(m):
        text = m.group(1)
        url = m.group(2)
        source = _get_source(url)
        return f"[Source-{source}]({url})"

    return re.sub(r'\[([^\]]*)\]\((https?://[^\)]+)\)', replacer, markdown)


def _origin_url(item: ExtractedItem) -> str:
    """原文地址：Reddit 等讨论型来源优先取站外原文链接"""
    return (item.metadata or {}).get("original_url") or item.url


def _annotate_items(markdown: str, items: list[ExtractedItem]) -> str:
    """Deterministically add the score and a readable origin URL per item."""
    lines = markdown.splitlines()
    for item in items:
        if not item.url:
            continue
        origin = _origin_url(item)
        for index, line in enumerate(lines):
            if item.url not in line and origin not in line:
                continue
            if "AI Score:" not in line:
                line = f"{line} **AI Score: {item.ai_score:.1f}/10**"
            if not line.rstrip().endswith(origin):
                line = f"{line} — {origin}"
            lines[index] = line
            break
    return "\n".join(lines)


def _items_to_json(items: list[ExtractedItem], brief: bool = False) -> str:
    """将新闻条目转为 JSON 字符串；brief=True 时只保留必要字段以节省 token"""
    import json

    data = []
    for item in items:
        if brief:
            data.append({
                "title": item.title,
                "summary": item.summary,
                "ai_score": item.ai_score,
                "source": item.source_type.value,
                "url": _origin_url(item),
            })
        else:
            data.append({
                "title": item.title,
                "summary": item.summary,
                "topics": item.topics,
                "ai_score": item.ai_score,
                "ai_reason": item.ai_reason,
                "score_tags": item.score_tags,
                "scoring_profile": item.scoring_profile,
                "source": item.source_type.value,
                "url": _origin_url(item),
            })
    return json.dumps(data, ensure_ascii=False, indent=2)


def _split_featured_brief(
    items: list[ExtractedItem],
) -> tuple[list[ExtractedItem], list[ExtractedItem]]:
    """按 ai_score 将新闻分为重点和简要两层

    items 已按 ai_score 降序排列（由 Scorer 保证）
    """
    top_k = settings.top_k_featured
    featured = items[:top_k]
    brief = items[top_k:]
    return featured, brief


async def _generate_description(top3: list[ExtractedItem], date: str) -> tuple[str, str]:
    """用 LLM 生成一句话日报摘要（英文+中文），降级时拼接标题"""
    fallback = " · ".join(
        (it.title[:40] + "...") if len(it.title) > 40 else it.title
        for it in top3
    )
    if not settings.openai_api_key or not top3:
        return fallback, fallback

    headlines = "\n".join(f"- {it.title}" for it in top3)
    prompt = (
        f"Based on these top AI news headlines from {date}, write TWO concise summary sentences:\n"
        f"1. ONE English sentence (max 25 words) capturing the day's most important AI developments.\n"
        f"2. ONE Chinese sentence (max 40 characters) translating/adapting the above.\n\n"
        f"Output ONLY two lines, no labels, no quotes:\n"
        f"Line 1: <English sentence>\n"
        f"Line 2: <Chinese sentence>\n\n"
        f"{headlines}"
    )
    try:
        llm = _build_llm()
        resp = await llm.ainvoke(prompt)
        lines = [l.strip().strip('"').strip("'") for l in resp.content.strip().splitlines() if l.strip()]
        desc_en = lines[0][:150] if lines else fallback
        desc_zh = lines[1][:150] if len(lines) > 1 else desc_en
        return desc_en, desc_zh
    except Exception as e:
        logger.warning(f"Description generation failed, falling back: {e}")
        return fallback, fallback


async def writer_node(state: PipelineState) -> dict:
    """Writer 节点：生成每日新闻简报（重点展开 + 快讯速览）"""
    extracted = state.get("extracted_items", [])
    if not extracted:
        logger.warning("No extracted items, skipping writing")
        return {"article": None}

    # 兼容旧配置；Profile threshold 已在 Scorer 阶段执行
    min_score = settings.min_importance_score
    before_count = len(extracted)
    extracted = [item for item in extracted if item.importance_score >= min_score]
    if before_count > len(extracted):
        logger.info(
            f"Filtered {before_count - len(extracted)} items below "
            f"importance_score {min_score}"
        )

    if not extracted:
        logger.warning("No items above min_importance_score, skipping writing")
        return {"article": None}

    today = (datetime.now(tz=timezone.utc) - timedelta(days=1)).strftime("%Y-%m-%d")
    featured, brief = _split_featured_brief(extracted)
    threshold = featured[-1].ai_score if featured else 0

    logger.info(
        f"Writing {today} newsletter: "
        f"featured {len(featured)} + brief {len(brief)} "
        f"(cutoff importance ≥ {threshold:.1f})"
    )

    groups = _group_by_topic(extracted)
    sections = [ArticleSection(topic=t, items=items) for t, items in groups.items()]

    # 尝试用 LLM 生成
    markdown = ""
    if settings.openai_api_key:
        try:
            llm = _build_llm()
            prompt = WRITER_PROMPT.format(
                date=today,
                total_count=len(extracted),
                featured_count=len(featured),
                brief_count=len(brief),
                threshold=threshold,
                featured_json=_items_to_json(featured),
                brief_json=_items_to_json(brief, brief=True),
            )
            resp = await llm.ainvoke(prompt)
            markdown = resp.content
            # 完整性检查：LLM 可能截断，缺少章节则降级
            required_sections = ["Top Stories", "Quick Bites"]
            missing = [s for s in required_sections if s not in markdown]
            if missing:
                logger.warning(f"LLM output incomplete, missing sections: {missing}, falling back to template")
                markdown = _build_fallback_markdown(extracted, today)
            else:
                # LLM output link labels may not be uniform, use post-processing to correct
                markdown = _normalize_source_links(markdown)
                logger.info("LLM writing complete")
        except Exception as e:
            logger.error(f"LLM writing failed, falling back to template: {e}")
            markdown = _build_fallback_markdown(extracted, today)
    else:
        logger.info("LLM not configured, using template")
        markdown = _build_fallback_markdown(extracted, today)

    # 用 LLM 生成一句话 description（双语）
    markdown = _annotate_items(markdown, extracted)

    top3 = sorted(extracted, key=lambda x: x.ai_score, reverse=True)[:3]
    description, description_zh = await _generate_description(top3, today)

    # 落地版：第二路 LLM 生成，失败只打 warning，不影响专业版
    markdown_dev = ""
    if settings.openai_api_key:
        try:
            llm_dev = _build_llm()
            dev_prompt = DEV_WRITER_PROMPT.format(
                date=today,
                total_count=len(extracted),
                items_json=_items_to_json(extracted),
            )
            dev_resp = await llm_dev.ainvoke(dev_prompt)
            markdown_dev = dev_resp.content
            if "已筛除条目说明" not in markdown_dev:
                logger.warning("Dev version missing filter section, falling back")
                markdown_dev = _build_fallback_dev_markdown(extracted, today)
            else:
                logger.info("Dev version writing complete")
        except Exception as e:
            logger.warning(f"Dev version LLM failed, falling back to template: {e}")
            markdown_dev = _build_fallback_dev_markdown(extracted, today)
    else:
        logger.info("LLM not configured, dev version using template")
        markdown_dev = _build_fallback_dev_markdown(extracted, today)

    description_dev = description_zh or description

    article = GeneratedArticle(
        title=f"AI Daily — {today}",
        date=today,
        description=description,
        description_zh=description_zh,
        description_dev=description_dev,
        sections=sections,
        markdown_content=markdown,
        markdown_content_dev=markdown_dev,
        item_count=len(extracted),
    )

    logger.info(f"Writing done: {article.title}, {article.item_count} items")
    return {"article": article}
