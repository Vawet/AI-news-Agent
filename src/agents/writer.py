def _source_label_for_url(url: str) -> str:
    """来源标签一律由 URL 域名决定，避免标签与链接指向不一致。"""
    for domain, label in _SOURCE_DOMAIN_MAP.items():
        if domain in url:
            return label
    return "rss"


